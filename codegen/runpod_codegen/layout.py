"""Split generated code into one Rust module per API area, one file per kind.

Each OpenAPI tag (Pods, Serverless, Templates, ...) becomes `src/api/<area>/`:

    mod.rs          the operations it covers, and re-exports
    operations.rs   `impl Client` methods; for a large area, `operations/`
                    with one file per sub-resource (`groups.rs`, `roles.rs`)
    models.rs       resources and their parts (`Pod`, `PodSsh`, ...)
    enums.rs        string enums (`PodStatus`, ...)
    requests.rs     request bodies and optional-parameter structs
    responses.rs    list pages and other answer wrappers

A file is left out when it would be empty. Where a type goes:

1. to the one area whose operations use it;
2. else, used by several areas or by none, to the area its name says it
   belongs to (`Pod*` to pods even though clusters lists pods too) -- see
   `HOME_PREFIXES`;
3. else to `src/api/common/`, laid out the same way.

Every generated file imports `crate::api::*`, so placement is purely about
where a reader finds a type: it never decides whether the code compiles.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

from .naming import snake
from .operations import Operation
from .spec import ROOT

API_DIR = ROOT / "src" / "api"
COMMON = "common"

# Name prefix -> area, for types more than one area uses. Longest match wins.
HOME_PREFIXES = {
    "Pod": "pods",
    "QueuedPod": "pods",
    "Cluster": "clusters",
    "Template": "templates",
    "NetworkVolume": "network_volumes",
    "GlobalVolume": "global_volumes",
    "Endpoint": "serverless",
    "Worker": "serverless",
    "Build": "serverless",
    "Release": "serverless",
    "Registry": "registries",
    "Delegation": "registries",
    "GpuType": "catalog",
    "CpuType": "catalog",
    "DataCenter": "catalog",
    "CostCenter": "cost_centers",
    "Tag": "tags",
    "Billing": "billing",
    "AuditLog": "audit_logs",
    "Organization": "organization",
    "Secret": "account",
    "SshKey": "account",
    "Account": "account",
    "Authentication": "signup",
}

KINDS = ("models", "enums", "requests", "responses")
KIND_DOCS = {
    "models": "Resources and their parts.",
    "enums": "String enums. Each has an `Other(String)` fallback for values added after this crate was generated.",
    "requests": "Request bodies, and the optional parameters of operations that take them.",
    "responses": "List pages and other answer wrappers.",
}

# An area's operations are split by sub-resource past this many lines.
SPLIT_OPERATIONS_OVER = 450

HEADER = "// @generated by codegen/generate.py from openapi/runpod-v2.json. Do not edit by hand.\n"
ALLOW = "#![allow(clippy::all, rustdoc::all)]\n"
IMPORTS = "#[allow(unused_imports)]\nuse crate::api::*;\n"


def module_name(tag: str) -> str:
    return snake(tag)


def references(src: str, names: set[str]) -> set[str]:
    """Type names a piece of Rust mentions outside its doc comments."""
    code = "\n".join(l for l in src.splitlines() if not l.lstrip().startswith("///"))
    return {t for t in re.findall(r"\b[A-Z][A-Za-z0-9_]*\b", code) if t in names}


def home(name: str) -> str | None:
    best = None
    for prefix, area in HOME_PREFIXES.items():
        # "Tag" must not claim "TagCondition"'s neighbour "Target"; require a
        # word boundary: end of name or an uppercase letter next.
        if name.startswith(prefix) and (len(name) == len(prefix) or name[len(prefix)].isupper()):
            if best is None or len(prefix) > len(best[0]):
                best = (prefix, area)
    return best[1] if best else None


def assign(items: dict[str, str], ops: list[Operation]) -> dict[str, str]:
    """Type name -> area module."""
    names = set(items)
    deps = {n: references(src, names) - {n} for n, src in items.items()}
    reachers: dict[str, set[str]] = {n: set() for n in names}

    def walk(roots: set[str], label: str):
        stack = list(roots)
        while stack:
            n = stack.pop()
            if label in reachers[n]:
                continue
            reachers[n].add(label)
            stack.extend(deps[n])

    for op in ops:
        walk(references(op.source, names), module_name(op.tag))

    owner = {}
    for n, r in reachers.items():
        if len(r) == 1:
            owner[n] = next(iter(r))
        else:
            owner[n] = home(n) or COMMON
    return owner


def kind(name: str, src: str) -> str:
    if re.search(r"^pub enum \w+ \{\n(.*\n)*?\s*Other\(String\),", src, re.M):
        return "enums"
    if name.endswith("Response"):
        return "responses"
    if name.endswith(("Params", "Request")) or re.match(r"(Create|Update|Verify|Resend)[A-Z]", name):
        return "requests"
    return "models"


def sub_resource(area: str, path: str) -> str:
    """`/v2/organization/groups/{id}/members` -> `groups`;
    `/v2/serverless/{id}/metrics/requests` -> `metrics`; the area's own
    collection -> `core`."""
    segments = [s for s in path.split("/")[3:] if not s.startswith("{")]
    return snake(segments[0]) if segments else "core"


def operations_files(d: Path, area: str, ops: list[Operation]) -> dict[Path, str]:
    def body(group: list[Operation]) -> str:
        src = "\n".join(op.source for op in group)
        client = "Client, Request, Retry, encode_segment" if "encode_segment(" in src else "Client, Request, Retry"
        return (
            HEADER
            + ALLOW
            + "\nuse reqwest::Method;\n\n"
            + IMPORTS
            + f"use crate::client::{{{client}}};\nuse crate::error::Error;\n\n"
            + "impl Client {\n"
            + src
            + "}\n"
        )

    groups: dict[str, list[Operation]] = {}
    for op in ops:
        groups.setdefault(sub_resource(area, op.path), []).append(op)
    lines = sum(op.source.count("\n") for op in ops)
    if len(groups) < 2 or lines <= SPLIT_OPERATIONS_OVER:
        return {d / "operations.rs": body(ops)}
    files = {d / "operations" / f"{g}.rs": body(group) for g, group in groups.items()}
    files[d / "operations" / "mod.rs"] = (
        HEADER + "\n//! One file per sub-resource; each adds methods to [`crate::Client`].\n\n"
        + "".join(f"mod {g};\n" for g in sorted(groups))
    )
    return files


def rustfmt(src: str) -> str:
    r = subprocess.run(
        ["rustfmt", "--edition", "2024", "--emit", "stdout"],
        input=src,
        capture_output=True,
        text=True,
    )
    if r.returncode != 0:
        sys.stderr.write(r.stderr)
        sys.exit("rustfmt failed on generated code")
    return r.stdout


def area_files(d: Path, title: str, items: dict[str, str], names: list[str], ops: list[Operation]) -> dict[Path, str]:
    by_kind = {k: [n for n in names if kind(n, items[n]) == k] for k in KINDS}
    present = [k for k in KINDS if by_kind[k]]
    files: dict[Path, str] = {}

    mod = HEADER + f"\n//! {title}\n"
    if ops:
        mod += f"//!\n//! {len(ops)} operations, as methods on [`crate::Client`]:\n//!\n"
        mod += "\n".join(f"//! - `{op.method} {op.path}`" for op in ops) + "\n"
    mod += "\n"
    if ops:
        mod += "mod operations;\n"
    for k in present:
        mod += f"mod {k};\n"
    mod += "\n"
    for k in present:
        mod += f"pub use {k}::*;\n"
    files[d / "mod.rs"] = mod

    for k in present:
        files[d / f"{k}.rs"] = (
            HEADER
            + f"\n//! {KIND_DOCS[k]}\n\n"
            + ALLOW
            + "\n"
            + IMPORTS
            + "\n"
            + "\n".join(items[n] for n in by_kind[k])
        )
    if ops:
        files |= operations_files(d, d.name, ops)
    return files


def render(items: dict[str, str], ops: list[Operation]) -> dict[Path, str]:
    """Every generated file, path -> formatted contents."""
    owner = assign(items, ops)
    tags: dict[str, str] = {}  # module -> tag, in spec order
    for op in ops:
        tags.setdefault(module_name(op.tag), op.tag)

    def names_in(module: str) -> list[str]:
        return sorted(n for n in items if owner[n] == module)

    files: dict[Path, str] = {}
    files |= area_files(API_DIR / COMMON, "Types more than one API area uses.", items, names_in(COMMON), [])
    for module, tag in tags.items():
        mine = [op for op in ops if module_name(op.tag) == module]
        files |= area_files(API_DIR / module, f"{tag}.", items, names_in(module), mine)

    mod_rs = HEADER + "\n//! Every Runpod API v2 area, one module each, generated from the OpenAPI document.\n\n"
    modules = [COMMON] + sorted(tags)
    mod_rs += "".join(f"pub mod {m};\n" for m in modules) + "\n"
    mod_rs += "".join(f"pub use {m}::*;\n" for m in modules)
    files[API_DIR / "mod.rs"] = mod_rs
    return {p: rustfmt(s) for p, s in files.items()}
