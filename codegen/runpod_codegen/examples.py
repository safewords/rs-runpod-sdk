"""A test that decodes every example in the spec into its Rust type.

Runpod's document carries request and response examples. Decoding each into
the generated type, then re-encoding it and comparing, catches a renamed or
mistyped field and a property the types do not model at all (it would be
dropped on the way back). Writes `tests/spec_examples.rs`; the checking
itself is hand-written in `tests/support/spec.rs`.
"""

from __future__ import annotations

from pathlib import Path

from .naming import rust_str
from .operations import Operation
from .spec import ROOT

TEST_FILE = ROOT / "tests" / "spec_examples.rs"


def render(ops: list[Operation]) -> dict[Path, str]:
    checks = []
    for op in ops:
        m, p = rust_str(op.method.lower()), rust_str(op.path)
        if op.request_type:
            checks.append(f"    s.request::<runpod::{op.request_type}>({p}, {m});")
        for status, t in sorted(op.response_types.items()):
            checks.append(f"    s.response::<runpod::{t}>({p}, {m}, {rust_str(status)});")
    src = (
        "// @generated by codegen/generate.py from openapi/runpod-v2.json. Do not edit by hand.\n\n"
        "mod support;\n\n"
        "/// Every request and response example in the spec decodes into its type\n"
        "/// and re-encodes to the same JSON.\n"
        "#[test]\n"
        "fn every_spec_example_round_trips() {\n"
        "    let mut s = support::spec::Examples::load();\n"
        + "\n".join(checks)
        + "\n    s.finish();\n}\n"
    )
    return {TEST_FILE: src}
